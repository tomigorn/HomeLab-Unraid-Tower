#!/usr/bin/env bash
#
# Pull the version-controllable parts of the live Unraid config into this repo.
#
# Run this, then `git diff`, to see drift between what the repo claims and what
# the server actually does. A repo that has silently diverged from the server is
# worse than no repo, because it will be trusted during a recovery.
#
# Secrets and licence keys are deliberately excluded.
#
# Usage:  ./deploy/fetch.sh

set -euo pipefail

HOST="${UNRAID_HOST:-tower}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

echo ">>> source: ${HOST}"

# The server powers itself off when idle (D10), so being unreachable is its
# normal resting state rather than an error. Wake it and wait for the array,
# otherwise every deploy/fetch would need a manual wake first.
ensure_awake() {
  local wake="${REPO_ROOT}/scripts/wake-tower.sh"
  if ssh -o BatchMode=yes -o ConnectTimeout=5 "$HOST" true 2>/dev/null; then
    return 0
  fi
  echo ">>> ${HOST} is not responding - waking it"
  [[ -x "$wake" ]] || { echo "!! ${wake} not found" >&2; return 1; }
  "$wake" || return 1
  ssh -o BatchMode=yes -o ConnectTimeout=5 "$HOST" true 2>/dev/null
}

if ! ensure_awake; then
  echo "!! cannot reach ${HOST} over SSH with key auth" >&2
  exit 1
fi

mkdir -p "${REPO_ROOT}"/config/{shares,ssh,notifications}

echo ">>> share configs"
rsync -av -e ssh "${HOST}:/boot/config/shares/" "${REPO_ROOT}/config/shares/" 2>/dev/null || echo "   (none yet)"

echo ">>> notification config"
rsync -av -e ssh \
  --include='*/' --include='*.cfg' --include='*.json' --exclude='*' \
  "${HOST}:/boot/config/plugins/dynamix/" "${REPO_ROOT}/config/notifications/" 2>/dev/null || echo "   (none yet)"

echo ">>> ssh public keys only"
rsync -av -e ssh \
  --include='authorized_keys' --include='*.pub' --include='*/' --exclude='*' \
  "${HOST}:/boot/config/ssh/" "${REPO_ROOT}/config/ssh/" 2>/dev/null || echo "   (none yet)"

echo ">>> User Scripts schedules"
# Job schedules live in this one file, not in the job directories. Without it a
# rebuild restores scripts that silently never run.
mkdir -p "${REPO_ROOT}/config/user-scripts"
scp -q "${HOST}:/boot/config/plugins/user.scripts/schedule.json" \
       "${REPO_ROOT}/config/user-scripts/schedule.json" 2>/dev/null || echo "   (none yet)"

echo ">>> go file"
scp -q "${HOST}:/boot/config/go" "${REPO_ROOT}/config/go" 2>/dev/null || echo "   (none)"

echo ">>> live state snapshot (reference only, not deployed back)"
ssh "$HOST" 'echo "# Live state — generated by deploy/fetch.sh, do not edit"; echo
  echo "## unraid version"; cat /etc/unraid-version
  echo; echo "## array"; grep -iE "mdState|mdNumDisks|fsState" /var/local/emhttp/var.ini
  echo; echo "## disks by-id"; ls /dev/disk/by-id/ | grep -vE "part[0-9]"
  echo; echo "## block devices"; lsblk -o NAME,SIZE,TYPE,MODEL,SERIAL,FSTYPE,LABEL
  echo; echo "## zfs"; zpool status 2>/dev/null || echo "no pools"
  echo; echo "## plugins"; ls /boot/config/plugins/ 2>/dev/null
' > "${REPO_ROOT}/docs/live-state.md" 2>/dev/null

echo ">>> done — now run: git diff"
