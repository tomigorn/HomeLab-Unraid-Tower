#!/usr/bin/env bash
#
# Pull the server's persistent config back into the repo, so `git diff` shows
# drift between what this repo claims and what the server actually does.
#
# A repo that has silently diverged from the server is worse than no repo,
# because it will be trusted during a recovery.
#
# Mirrors the same tree as deploy.sh: boot/ here <-> /boot/ there.
# Secrets and the licence key are never pulled.
#
# Usage:  ./deploy/fetch.sh   then:   git diff

set -euo pipefail

HOST="${UNRAID_HOST:-tower}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="${REPO_ROOT}/boot/"

RSYNC_OPTS=(-rlt --no-perms --no-owner --no-group)

# Only these paths are version-controlled. Everything else on the flash is
# either machine-generated, binary, or secret.
INCLUDES=(
  --include 'config/'
  --include 'config/go'
  --include 'config/shares/'      --include 'config/shares/*.cfg'
  --include 'config/scripts/'     --include 'config/scripts/**'
  --include 'config/plugins/'
  --include 'config/plugins/user.scripts/'
  --include 'config/plugins/user.scripts/schedule.json'
  --include 'config/plugins/user.scripts/scripts/'
  --include 'config/plugins/user.scripts/scripts/**'
  # SSH public keys only. Restoring access after a flash failure needs to know
  # which keys were authorised; the private and host keys are excluded below and
  # by .gitignore.
  --include 'config/ssh/'
  --include 'config/ssh/root/'
  --include 'config/ssh/root/authorized_keys'
  --include 'config/ssh/*.pub'
  --exclude '*'
)

echo ">>> source: ${HOST}:/boot/"

ensure_awake() {
  ssh -o BatchMode=yes -o ConnectTimeout=5 "$HOST" true 2>/dev/null && return 0
  echo ">>> ${HOST} is not responding - waking it"
  "${REPO_ROOT}/bin/wake-tower.sh" || return 1
  ssh -o BatchMode=yes -o ConnectTimeout=5 "$HOST" true 2>/dev/null
}
ensure_awake || { echo "!! cannot reach ${HOST} over SSH with key auth" >&2; exit 1; }

rsync "${RSYNC_OPTS[@]}" "${INCLUDES[@]}" -e ssh "${HOST}:/boot/" "$DEST"

# Reference snapshot of live state. Not deployed back - documentation only.
echo ">>> live state snapshot -> docs/live-state.md"
ssh "$HOST" '
  echo "# Live state - generated by deploy/fetch.sh, do not edit"; echo
  echo "## unraid";        cat /etc/unraid-version; uptime -p
  echo; echo "## array";   grep -iE "mdState|mdNumDisks|fsState" /var/local/emhttp/var.ini
  echo; echo "## zfs";     zpool status 2>/dev/null | sed -n "1,12p"
  echo; echo "## datasets"; zfs list -o name,used,avail 2>/dev/null | grep -v "data/system/"
  echo; echo "## disks";   lsblk -o NAME,SIZE,TYPE,MODEL,SERIAL,FSTYPE
  echo; echo "## containers"; docker ps --format "{{.Names}}\t{{.Status}}" 2>/dev/null
  echo; echo "## scheduled jobs"; grep "user.scripts/scripts" /etc/cron.d/root 2>/dev/null | sed -E "s#.*scripts/([a-z-]+)/script.*#\1#"
  echo; echo "## plugins"; ls /boot/config/plugins/*.plg 2>/dev/null | xargs -n1 basename
' > "${REPO_ROOT}/docs/live-state.md" 2>/dev/null || echo "   (snapshot failed)"

echo ">>> done - now run: git diff"
